#!/usr/bin/env python3
"""ISS26 v0.9.5 Test14: guarded pixels -> independent clean-original XOR patch.

Requires the author's verified Cape Verde pixel edit list and a copy of the
published, SHA-pinned Test13 patch. All other decoded texture pixels must
remain identical. The unmodified EU Track01 is only read, never overwritten.
No unverified pixel coordinates are invented or generated by this tool.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from probe_v095_name_gpu_atlas import (
    CLEAN_SHA, TEST13_SHA, GROUPS, directory_files, file_sha,
    parse_patch, resource_data,
)
from v095_name_lz_codec import decode_atlas, repack_atlas, atlas_records
from build_v095_targeted_name_overlay import build, validate_manifest

TEST13_ATLAS_SHA = "01B9CCAAC6FF79372E30A3595AA98B9E41E6A6BA508ABABE77362829CF13300E"
FORM1 = 2048
CHUNK = 256


def sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest().upper()


def verify_pixel_edits(spec: dict) -> list[dict]:
    if (spec.get("schema_version") != 1 or spec.get("target") != "Cape Verde"
            or spec.get("screen") != "prematch_name"
            or spec.get("verified_gpu_capture") is not True):
        raise ValueError("Cape Verde pixel edits require an explicitly verified GPU capture")
    edits = spec.get("pixel_edits")
    if not isinstance(edits, list) or not 1 <= len(edits) <= 8192:
        raise ValueError("Require 1..8192 verified 4bpp pixel edits")
    seen = set()
    for edit in edits:
        if not isinstance(edit, dict) or set(edit) != {"tile", "x", "y", "old", "new"}:
            raise ValueError("Pixel edit must have only tile/x/y/old/new")
        if any(type(edit[k]) is not int for k in ("tile", "x", "y", "old", "new")):
            raise ValueError("Pixel edit fields must be integers")
        tile, x, y, before, after = (edit[k] for k in ("tile", "x", "y", "old", "new"))
        if not (0 <= tile < 26 and 0 <= x < 128 and 0 <= y < 128
                and 0 <= before < 16 and 0 <= after < 16 and before != after):
            raise ValueError("Out-of-bounds or no-op pixel edit")
        if (tile, x, y) in seen:
            raise ValueError("Duplicate pixel edit")
        seen.add((tile, x, y))
    return edits


def change_pixels(tiles: list[bytes], edits: list[dict]) -> list[bytes]:
    output = [bytearray(tile) for tile in tiles]
    for e in edits:
        index, x, y = e["tile"], e["x"], e["y"]
        offset, shift = y*64 + x//2, (x%2)*4
        current = (output[index][offset] >> shift) & 15
        if current != e["old"]:
            raise ValueError(f"Test13 sprite pixel mismatch at {index}:{x}:{y}")
        output[index][offset] = ((output[index][offset] & ~(15 << shift))
                                 | (e["new"] << shift))
    return [bytes(tile) for tile in output]


def generate_manifest(track: Path, test13: bytes, spec: dict) -> dict:
    if file_sha(track) != CLEAN_SHA:
        raise ValueError("Only the pinned clean European Track01 is supported")
    edits = verify_pixel_edits(spec)
    records = parse_patch(test13)  # SHA-pinned, 1492 records and original guards
    output = {"schema_version": 1, "target_label": "Cape Verde",
              "target_screen": "prematch_team_name", "edits": []}
    all_original = []
    all_changed = []
    with track.open("rb") as source:
        catalog = directory_files(source)
        for name, lbas in GROUPS.items():
            if name not in catalog:
                raise ValueError("Missing atlas resource " + name)
            lba, size = catalog[name]
            if size != 56256 or tuple(range(lba, lba+28)) != tuple(lbas):
                raise ValueError("Unexpected T_NAME CD extent")
            _, before, seen = resource_data(source, lba, size, records)
            if seen != set(lbas) or sha(before) != TEST13_ATLAS_SHA:
                raise ValueError("Test13 atlas content or record coverage changed")
            original = decode_atlas(before)
            modified = change_pixels(original, edits)
            rebuilt, meta = repack_atlas(before, modified)
            if meta["free_bytes"] < 0 or decode_atlas(rebuilt) != modified:
                raise AssertionError("GPU atlas repack failed")
            if [(x["x_words"],x["y"]) for x in atlas_records(before)] != [
                (x["x_words"],x["y"]) for x in atlas_records(rebuilt)]:
                raise AssertionError("GPU geometry modified")
            all_original.append([sha(tile) for tile in original])
            all_changed.append([sha(tile) for tile in modified])
            # The entire compressed atlas may shift even when only one
            # decoded pixel changes. Each 256-byte chunk is length-preserving.
            for j, sector in enumerate(lbas):
                a, b = before[j*FORM1:(j+1)*FORM1], rebuilt[j*FORM1:(j+1)*FORM1]
                if len(a) != len(b):
                    raise ValueError("Changed name atlas file allocation")
                for at in range(0, len(a), CHUNK):
                    old, new = a[at:at+CHUNK], b[at:at+CHUNK]
                    if old != new:
                        output["edits"].append({
                            "resource": name.split("/")[-1], "lba": sector,
                            "sector_offset": 24+at,
                            "expected_patched_hex": old.hex(),
                            "replacement_patched_hex": new.hex(),
                        })
    if len({tuple(row) for row in all_original}) != 1 or len({
        tuple(row) for row in all_changed}) != 1:
        raise ValueError("Test13 language atlases differ at decoded-pixel level")
    if not (1 <= len(output["edits"]) <= 1024):
        raise ValueError("Unsafe atlas manifest size")
    validate_manifest(output)
    return output


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--clean-track", required=True, type=Path)
    p.add_argument("--test13", required=True, type=Path)
    p.add_argument("--pixel-edits", required=True, type=Path)
    p.add_argument("--manifest", required=True, type=Path)
    p.add_argument("--output", required=True, type=Path)
    p.add_argument("--report", required=True, type=Path)
    a = p.parse_args()
    spec = json.loads(a.pixel_edits.read_text(encoding="utf-8"))
    test13 = a.test13.read_bytes()
    edits = generate_manifest(a.clean_track, test13, spec)
    a.manifest.parent.mkdir(parents=True,exist_ok=True)
    a.manifest.write_text(json.dumps(edits, indent=2)+"\n", encoding="utf-8")
    result = build(a.clean_track, a.test13, a.manifest, a.output, a.report)
    print("Test14 CANDIDATE ONLY: no game/visual verification yet")
    print("Independent clean-original XOR patch:", result["output_patch_sha256"])


if __name__ == "__main__":
    main()
